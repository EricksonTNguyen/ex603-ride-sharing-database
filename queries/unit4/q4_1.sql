    pickup_city,
    driver_id,
    COUNT(*) AS trip_count,
    AVG(
        CASE
            WHEN trip_status <> 'completed' THEN 1.0
            ELSE 0.0
        END
    ) AS failure_rate,
    AVG(fare_amount) AS average_fare
FROM trips
GROUP BY pickup_city, driver_id
