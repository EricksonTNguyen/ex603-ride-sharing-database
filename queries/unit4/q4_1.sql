-- 4.1.1 Calculate the count, total, average, minimum, and maximum of the ridesharing event metrics
-- Requirement: SELECT, COUNT, SUM, AVG, MIN, MAX, DISTINCT.

SELECT
    COUNT(fare_amount) AS fare_count,
    SUM(fare_amount) AS total_fare,
    AVG(fare_amount) AS average_fare,
    MIN(fare_amount) AS minimum_fare,
    MAX(fare_amount) AS maximum_fare,
    COUNT(DISTINCT rider_id) AS distinct_riders
FROM trips;

