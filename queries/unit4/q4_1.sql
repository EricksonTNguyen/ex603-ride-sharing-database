-- 4.1.3 Calculate the the failure rate based off an chosen minimum threshold (10). The threshold of 10 was chosen to not ding drivers with low trips which would inflate their failure rate. 
-- THRESHOLD DECISION: The threshold of 10 was chosen to not ding drivers with low trips which would inflate their failure rate. It was chosen as a good middle ground between each driver's total number of trips
-- Requirement: SELECT, COUNT, AVG, CASE, WHEN, GROUP BY, HAVING, ORDER BY.

SELECT
    driver_id,
    COUNT(*) AS trip_count,
    AVG(
        CASE
            WHEN trip_status <> 'completed' THEN 1.0
            ELSE 0.0
        END
    ) AS failure_rate
FROM trips
GROUP BY driver_id
HAVING COUNT(*) >= 10
ORDER BY failure_rate DESC;

